<?php

namespace App\Services\Assistant;

use Laravel\Ai\Attributes\MaxTokens;
use Laravel\Ai\Attributes\Provider;
use Laravel\Ai\Attributes\Timeout;
use Laravel\Ai\Contracts\Agent;
use Laravel\Ai\Promptable;
use Stringable;

/**
 * Модель ответа ИИ-помощника: пишет ответ только по найденным фрагментам библиотеки и ставит сноски [n].
 * Ссылки на PDF модель не пишет: их собирает код по номерам сносок. Запас max_tokens нужен на рассуждение модели.
 * Без temperature: модели GPT в шлюзе её не принимают.
 */
#[Provider('beget')]
#[MaxTokens(3000)]
#[Timeout(90)]
class LibraryAnswerAgent implements Agent
{
    use Promptable;

    public const string NOT_FOUND = 'НЕТ_ОТВЕТА';

    public function instructions(): Stringable|string
    {
        return <<<'TEXT'
            Ты помощник врача на сайте MagExpert. Отвечай только по фрагментам документов из библиотеки, которые даны в сообщении.

            Правила:
            - Используй только сведения из фрагментов. Ничего не добавляй от себя и из общих знаний.
            - После каждого утверждения ставь сноску с номером фрагмента в квадратных скобках, например [2] или [1][3].
            - Числа, дозировки, единицы измерения и названия препаратов переписывай точно как во фрагменте.
            - Отвечай на языке вопроса. Если вопрос на русском, а фрагменты на английском, переведи суть на русский, термины можно дать в скобках по-английски.
            - Пиши коротко и по делу: 2–6 предложений или короткий список. Абзацы разделяй пустой строкой. Без Markdown-заголовков и таблиц.
            - Не пиши ссылки, названия файлов и номера страниц: их покажет сайт по номерам сносок.
            - Если во фрагментах нет ответа на вопрос, ответь ровно одним словом: НЕТ_ОТВЕТА
            TEXT;
    }
}
