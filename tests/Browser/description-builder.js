async (page) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.route('**/event-editor/**', async route => { const url = new URL(route.request().url()); const response = await route.fetch({ url: 'http://127.0.0.1:8000' + url.pathname }); await route.fulfill({ response }); });
    await page.goto('http://127.0.0.1:5178/@vite/client');
    await page.evaluate(async () => {
        const { createApp, h, ref } = await import('/node_modules/.vite/deps/vue.js');
        const { default: Builder } = await import('/resources/js/Components/Form/DescriptionBuilder.vue');
        document.body.innerHTML = '<div id="test"></div>';
        window.output = ''; window.saveRequests = 0;
        window.axios = { post: async (url, body) => ({ data: await (await fetch(url, { method: 'POST', body })).json() }) };
        const value = ref('<h2>Программа</h2><p>Описание мероприятия</p><p><a href="https://example.com/register" style="display:inline-block;padding:12px;background:#f27b63">Регистрация</a></p>');
        window.builder = ref(null);
        createApp({ render: () => h(Builder, { ref: window.builder, modelValue: value.value, 'onUpdate:modelValue': v => { value.value = v; window.output = v; }, uploadEndpoint: '/upload', onSave: () => window.saveRequests++ }) }).mount('#test');
    });
    const frame = page.frameLocator('iframe');
    await frame.locator('.be-canvas').getByText('Описание мероприятия', { exact: true }).waitFor();
    if (await frame.getByRole('button', { name: 'Применить', exact: true }).count()) throw new Error('Duplicate apply button remains');
    if (await page.evaluate(() => window.output) !== '') throw new Error('Loading must preserve the existing HTML');
    await frame.locator('.be-canvas').getByText('Описание мероприятия', { exact: true }).click();
    const editor = frame.locator('.be-canvas .tiptap');
    await editor.fill('Редактируем прямо на холсте');
    await page.waitForFunction(() => window.output.includes('Редактируем прямо на холсте'));
    await editor.press('Control+s');
    await page.waitForFunction(() => window.saveRequests === 1);
    const textBox = await editor.boundingBox();
    const toolbar = await frame.locator('.be-fmt').boundingBox();
    if (toolbar.y + toolbar.height > textBox.y + 1) throw new Error('Format toolbar overlaps the edited text');
    if (await frame.locator('.be-right .tiptap').count()) throw new Error('Text editor must be on the canvas');
    if (await frame.getByRole('button', { name: 'Переменная', exact: true }).count()) throw new Error('Variable control must be hidden');
    const side = await frame.locator('.be-right').boundingBox();
    const canvas = await frame.locator('.be-canvas').boundingBox();
    if (side.x < canvas.x + canvas.width - 3) throw new Error('Inspector must stay beside the canvas');
    const tiles = await frame.locator('.be-tile').all();
    const first = await tiles[0].boundingBox();
    const second = await tiles[1].boundingBox();
    if (Math.abs(first.x - second.x) > 1 || second.y <= first.y) throw new Error('Palette must be a vertical list');
    await frame.getByRole('button', { name: 'Кнопка', exact: true }).click();
    await frame.getByLabel('Текст кнопки', { exact: true }).fill('Очное участие');
    await frame.getByLabel('Ссылка', { exact: true }).fill('https://example.com/new');
    await frame.getByRole('button', { name: 'Зеро-блок', exact: true }).click();
    await frame.getByRole('button', { name: 'Редактировать слои', exact: true }).first().click();
    await frame.locator('.ze').waitFor();
    if (await frame.locator('.ze-layers').count() !== 1) throw new Error('Original ZeroEditor did not open');
    await page.screenshot({ path: '/tmp/magsender-zero-editor.png', fullPage: true });
    await frame.locator('.ze').getByLabel('Высота холста', { exact: true }).fill('300');
    await frame.getByRole('button', { name: 'Готово', exact: true }).click();
    await page.route('**/images/default-event-cover.webp', async route => { await route.fulfill({ response: await route.fetch({ url: 'http://127.0.0.1:8000/images/default-event-cover.webp' }) }); });
    await page.route('**/upload', route => route.fulfill({ json: { url: '/images/default-event-cover.webp' } }));
    const html = await page.evaluate(async () => await window.builder.value.flush());
    if (!html.includes('data-magsender-design') || !html.includes('Очное участие') || !html.includes('Редактируем прямо на холсте')) throw new Error('Description serialization failed');
    await page.evaluate(() => { const f = document.querySelector('iframe'); f.contentWindow.postMessage({ channel: 'magexpert-description', type: 'init', html: window.output }, location.origin); });
    await frame.getByText('Редактируем прямо на холсте', { exact: true }).waitFor();
    await frame.locator('.be-canvas').getByText('Редактируем прямо на холсте', { exact: true }).click();
    await frame.locator('.be-canvas .tiptap').fill(('Длинное описание мероприятия. ').repeat(300));
    await page.waitForFunction(() => { const f = document.querySelector('iframe'); return f.clientHeight > 1200 && f.contentDocument.documentElement.scrollHeight <= f.clientHeight + 2; });
    await page.screenshot({ path: '/tmp/magsender-event-editor.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile page overflow');
    if (errors.length) throw new Error(errors.join('\n'));
    return { sharedMagSenderEditor: true, inlineEditing: true, verticalPalette: true, originalZeroEditor: true, saveAndReload: true };
};
